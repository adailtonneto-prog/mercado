-- Execute este script no Supabase: SQL Editor > New query > Run
create table if not exists public.produtos (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nome text not null,
  categoria text,
  quantidade numeric(12, 2) not null default 0 check (quantidade >= 0),
  preco numeric(12, 2) not null default 0 check (preco >= 0),
  created_at timestamptz not null default now()
);

alter table public.produtos enable row level security;

-- ATENÇÃO: políticas abertas para o protótipo sem login.
-- Qualquer pessoa com acesso ao site pode consultar, inserir, alterar e excluir.
-- Para uso real, implemente autenticação e restrinja estas políticas.
drop policy if exists "Acesso público para protótipo" on public.produtos;

create policy "Acesso público para protótipo"
on public.produtos
for all
to anon, authenticated
using (true)
with check (true);

grant select, insert, update, delete on public.produtos to anon, authenticated;
grant usage, select on sequence public.produtos_id_seq to anon, authenticated;
